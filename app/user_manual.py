def _section_images(section_id: str) -> list[dict]:
    out: list[dict] = []
    for img in SECTION_IMAGES.get(section_id) or []:
        file_name = img["file"]
        caption = img.get("caption") or ""
        out.append(
            {
                "file": file_name,
                "src": f"/static/user_manual/{file_name}",
                "path": f"user_manual/{file_name}",
                "caption": caption,
                "alt": caption or file_name,
            }
        )
    return out


def manual_sections() -> list[dict]:
    """نسخة من الأقسام مع ترقيم الخطوات والصور التعليمية."""
    out: list[dict] = []
    for sec in MANUAL_SECTIONS:
        steps = []
        for i, st in enumerate(sec.get("steps") or [], start=1):
            row = dict(st)
            row["n"] = i
            steps.append(row)
        item = dict(sec)
        item["steps"] = steps
        item["images"] = _section_images(sec.get("id") or "")
        item["paragraphs"] = [sec.get("intro") or ""]
        if sec.get("audience"):
            item["paragraphs"].insert(0, f"الجمهور المستهدف: {sec['audience']}")
        item["bullets"] = list(sec.get("tips") or [])
        out.append(item)
    return out
